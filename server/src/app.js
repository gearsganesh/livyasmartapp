import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import rateLimit from 'express-rate-limit';
import authRoutes from './routes/auth.routes.js';
import resourceRoutes from './routes/resources.routes.js';
import { errorHandler } from './middleware/errorHandler.js';
const app=express();
const allowedOrigins=new Set((process.env.CLIENT_ORIGINS||process.env.CLIENT_ORIGIN||'').split(',').map(origin=>origin.trim()).filter(Boolean));
if(!allowedOrigins.size)throw new Error('CLIENT_ORIGINS (or legacy CLIENT_ORIGIN) must be configured.');
if(!process.env.JWT_SECRET||Buffer.byteLength(process.env.JWT_SECRET)<32)throw new Error('JWT_SECRET must contain at least 32 bytes.');
app.disable('x-powered-by');app.set('trust proxy',process.env.TRUST_PROXY==='true'?1:false);app.use(helmet());
app.use(cors({origin(origin,callback){if(!origin||allowedOrigins.has(origin))return callback(null,true);return callback(null,false);},credentials:true,methods:['GET','POST','PATCH','PUT','DELETE','OPTIONS'],allowedHeaders:['Content-Type','X-CSRF-Token']}));
app.use((req,res,next)=>{if(['POST','PATCH','PUT','DELETE'].includes(req.method)&&req.headers.origin&&!allowedOrigins.has(req.headers.origin))return res.status(403).json({error:'Origin not allowed.'});next();});
app.use(express.json({limit:'100kb'}));app.use(cookieParser());
app.get('/api/health',async(req,res)=>res.json({status:'ok',service:'livyacurehub-api'}));
app.use('/api/',rateLimit({windowMs:60000,limit:120,standardHeaders:true,legacyHeaders:false}));
app.use('/api/auth',authRoutes);app.use('/api',resourceRoutes);
app.use((req,res)=>res.status(404).json({error:'Endpoint not found.'}));app.use(errorHandler);
export default app;
